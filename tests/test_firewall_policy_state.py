def test_first_install_publishes_only_after_matching_commit_and_noops(machine):
    rules = source(b"counter accept")
    assert policy.inspect() == {
        "state": "fresh",
        "runtime": None,
        "source": None,
        "verified_runtime": None,
    }
    result = policy.apply(rules)
    assert result == {"changed": True, "attempt": machine.armed}
    assert policy.verified_file() is None
    assert policy.owned_by(machine.current, result["attempt"])
    with pytest.raises(policy.PolicyError, match="awaiting SSH"):
        policy.load_verified()
    with pytest.raises(policy.PolicyError, match="does not match"):
        policy.commit("a" * 64)
    policy.commit(result["attempt"])

    meta, batch = policy.verified_file()
    assert batch.endswith(policy.REPLACE + snapshot(b"counter accept"))
    assert meta.runtime == policy.live_digest(machine.current)
    assert meta.source == policy.digest(rules)
    assert machine.armed is None
    assert policy.pending_file() is None
    assert policy.apply(rules) == {"changed": False, "attempt": None}
    machine.current = None  # The /run transaction is already gone when the unit starts at boot.
    policy.load_verified()
    assert machine.current == snapshot(b"counter accept")
    assert policy.apply(rules) == {"changed": False, "attempt": None}


def test_expired_first_install_retries_and_stale_callback_is_a_noop(machine):
    original = policy.apply(source(b"counter accept"))["attempt"]
    machine.now = policy.pending_file().deadline
    with pytest.raises(policy.PolicyError, match="expired"):
        policy.commit(original)
    assert policy.inspect()["state"] == "fresh"
    assert machine.current is not None  # Inspect never changes kernel rules.
    retry = policy.apply(source(b"counter drop"))["attempt"]
    assert retry != original
    assert machine.armed == retry
    assert policy.owned_by(machine.current, retry)
    policy.rollback(original)
    assert policy.owned_by(machine.current, retry)
    policy.rollback(retry)
    assert machine.current is None
    assert policy.pending_file() is None


def test_changed_install_rolls_back_without_touching_other_files(machine):
    original = source(b"counter accept")
    accept(original)
    baseline = policy.verified_file()
    unrelated_policy = policy.POLICY_DIR / "operator.nft"
    unrelated_runtime = policy.RUNTIME_DIR / "operator-state"
    unrelated_policy.write_bytes(b"other policy")
    unrelated_runtime.write_bytes(b"other state")
    changed = policy.apply(source(b"counter drop"))["attempt"]
    assert policy.verified_file() == baseline
    machine.timer_state = "running"
    policy.rollback(changed)
    assert policy.verified_file() == baseline
    assert machine.current == snapshot(b"counter accept")
    assert policy.pending_file() is None
    assert machine.armed is None
    assert unrelated_policy.read_bytes() == b"other policy"
    assert unrelated_runtime.read_bytes() == b"other state"


def test_failures_before_and_after_activation_reconcile(machine, monkeypatch):
    rules = source(b"counter accept")

    def fail_arm(_attempt):
        raise policy.PolicyError("arm failed")

    with monkeypatch.context() as scoped:
        scoped.setattr(policy, "arm", fail_arm)
        with pytest.raises(policy.PolicyError, match="arm failed"):
            policy.apply(rules)
    assert machine.mutations == []
    assert policy.pending_file() is None

    write_pending = policy.write_pending

    def fail_write(pending):
        if pending.runtime:
            raise OSError("activation receipt unavailable")
        write_pending(pending)

    monkeypatch.setattr(policy, "write_pending", fail_write)
    with pytest.raises(OSError, match="activation receipt unavailable"):
        policy.apply(rules)
    assert machine.current is None
    assert policy.pending_file() is None
    assert machine.armed is None
    assert [rule == b"delete table inet steward\n" for rule in machine.mutations] == [False, True]


def test_failed_commit_does_not_promote_and_failed_disarm_keeps_published_policy(
    machine, monkeypatch
):
    accept(source(b"counter accept"))
    previous = policy.verified_file()
    candidate = source(b"counter drop")
    attempt = policy.apply(candidate)["attempt"]
    before_drift = machine.current
    machine.current = snapshot(b"counter accept")
    with pytest.raises(policy.PolicyError, match="changed during SSH"):
        policy.commit(attempt)
    assert policy.verified_file() == previous
    machine.current = before_drift

    def fail_disarm(_attempt):
        raise policy.PolicyError("could not disarm")

    with monkeypatch.context() as scoped:
        scoped.setattr(policy, "disarm", fail_disarm)
        with pytest.raises(policy.PolicyError, match="could not disarm"):
            policy.commit(attempt)

    promoted = policy.verified_file()
    assert promoted[1].endswith(policy.REPLACE + snapshot(b"counter drop"))
    policy.rollback(attempt)
    assert policy.verified_file() == promoted
    assert policy.owned_by(machine.current, attempt)
    assert policy.pending_file() is None


def test_expired_pending_cannot_delete_a_different_table(machine):
    attempt = policy.apply(source(b"counter accept"))["attempt"]
    machine.current = snapshot(b"counter drop")
    with pytest.raises(policy.PolicyError, match="without the pending attempt marker"):
        policy.rollback(attempt)
    assert machine.current == snapshot(b"counter drop")
    assert policy.pending_file().attempt == attempt


def test_unknown_timer_prevents_expired_attempt_recovery(machine):
    policy.apply(source(b"counter accept"))
    machine.now = policy.pending_file().deadline
    machine.unknown = True
    mutations = machine.mutations.copy()
    with pytest.raises(policy.PolicyError, match="timer state is unknown"):
        policy.apply(source(b"counter drop"))
    assert machine.mutations == mutations


def test_rollback_restores_verified_when_known_previous_runtime_was_missing(machine):
    accept(source(b"counter accept"))
    machine.current = None
    attempt = policy.apply(source(b"counter drop"))["attempt"]
    machine.current = None
    policy.rollback(attempt)
    assert machine.current == snapshot(b"counter accept")


def test_conflicting_timer_is_never_disarmed_or_used_by_pending_attempt(machine):
    attempt = policy.apply(source(b"counter accept"))["attempt"]
    machine.armed = "a" * 64
    with pytest.raises(policy.PolicyError, match="another attempt"):
        policy.rollback(attempt)
    assert policy.owned_by(machine.current, attempt)
    assert machine.armed == "a" * 64


