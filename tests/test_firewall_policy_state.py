def test_rollback_cli_waits_longer_for_a_transaction_in_progress(machine, monkeypatch):
    attempt = policy.apply(source(b"counter accept"))["attempt"]
    acquired = []
    lock = policy.policy_lock

    def observe(wait_seconds):
        acquired.append(wait_seconds)
        return lock(wait_seconds)

    monkeypatch.setattr(policy, "policy_lock", observe)
    monkeypatch.setattr(policy.sys, "argv", ["firewall-policy", "rollback", attempt])
    policy.main()
    assert acquired == [policy.ROLLBACK_LOCK_WAIT]
    assert acquired[0] > policy.ROLLBACK_SECONDS


def test_verified_bytes_must_match_the_recorded_runtime(machine):
    accept(source(b"counter accept"))
    verified = policy.POLICY_DIR / policy.POLICY_FILE
    policy.publish(verified, verified.read_bytes().replace(b"counter accept", b"counter drop"))
    machine.current = None
    with pytest.raises(policy.PolicyError, match="contents fail integrity"):
        policy.load_verified()
    assert machine.current is None


@pytest.mark.parametrize(
    "state", ["no-lock", "absent", "pending", "stale-source", "stale-runtime", "verified"]
)
def test_require_active_binds_exact_source_and_live_table(machine, monkeypatch, state):
    rules = source(b"counter accept")
    expected = policy.digest(rules)
    if state != "no-lock":
        with policy.policy_lock():
            pass
    if state == "pending":
        policy.apply(rules)
    elif state not in {"no-lock", "absent"}:
        accept(rules)
    if state == "stale-source":
        expected = policy.digest(rules + b"\n")
    if state == "stale-runtime":
        machine.current = snapshot(b"counter drop")

    before = machine.mutations.copy()
    verified = policy.verified_file()
    pending = policy.pending_file()
    monkeypatch.setattr(policy.sys, "argv", ["firewall-policy", "require-active", expected])
    if state == "verified":
        policy.main()
    else:
        with pytest.raises(SystemExit) as exc:
            policy.main()
        assert exc.value.code == 1
    assert machine.mutations == before
    assert policy.verified_file() == verified
    assert policy.pending_file() == pending
    if state == "no-lock":
        assert not (policy.RUNTIME_DIR / "lock").exists()
