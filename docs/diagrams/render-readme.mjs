import { readFile, writeFile } from "node:fs/promises";
import { render, THEMES } from "@grethel-labs/excaliplant";

const directory = new URL("./readme/", import.meta.url);
const source = await readFile(new URL("operations.puml", directory), "utf8");
const title = "The OpsTend operating cycle";
const description = "Validate YAML, harden the host, deploy isolated workloads, observe their health, run guarded actions when needed and recheck.";
const palettes = {
  light: {
    base: "pastel-light",
    canvas: "#f7fbfa",
    panel: "#ffffff",
    ink: "#172e32",
    line: "#c9ddd7",
    accent: "#0b7168",
  },
  dark: {
    base: "grethel-labs-dark",
    canvas: "#111827",
    panel: "#1b3038",
    ink: "#f7f8fa",
    line: "#315058",
    accent: "#2db8a8",
  },
};

for (const [mode, palette] of Object.entries(palettes)) {
  const base = THEMES[palette.base];
  const result = await render(source, {
    strict: true,
    theme: {
      ...base,
      background: palette.canvas,
      surface: palette.panel,
      ink: palette.ink,
      roles: {
        ...base.roles,
        default: { ...base.roles.default, fill: palette.panel },
      },
    },
  });
  const diagram = await result.toSvg({ background: "transparent", padding: 18 });
  const dimensions = diagram.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!dimensions || !diagram.includes("stroke-dasharray")) {
    throw new Error("The README diagram needs a viewBox and a dashed recheck path.");
  }
  const [, width, height] = dimensions.map(Number);
  // The dashed edge marks the return to observation after a guarded action.
  const frame = `
<title id="title">${title}</title>
<desc id="description">${description}</desc>
<defs>
  <pattern id="grid" width="14" height="14" patternUnits="userSpaceOnUse">
    <circle cx="7" cy="7" r=".65" fill="${palette.line}" />
  </pattern>
  <style>
    [stroke-dasharray] { stroke: ${palette.accent}; }
    @media (prefers-reduced-motion: no-preference) {
      [stroke-dasharray] { animation: recheck 2s ease-in-out 2; }
      @keyframes recheck { 50% { stroke-width: 3; } }
    }
  </style>
</defs>
<rect x=".5" y=".5" width="${width - 1}" height="${height - 1}" rx="16" fill="${palette.canvas}" stroke="${palette.line}" />
<rect x="9" y="9" width="${width - 18}" height="${height - 18}" rx="9" fill="url(#grid)" />
`;
  const svg = diagram.replace(/^(<svg[^>]*)(>)/, `$1 role="img" aria-labelledby="title description"$2${frame}`);
  const comment = "<!-- Generated by docs/diagrams/render-readme.mjs from operations.puml. -->";
  await writeFile(new URL(`operations-${mode}.svg`, directory), `${comment}\n${svg}\n`);
}
