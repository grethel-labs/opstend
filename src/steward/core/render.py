def _hardening(memory_mb: int, cpus: float, pids: int) -> list[str]:
    return [
        "ReadOnly=true",
        "NoNewPrivileges=true",
        "DropCapability=all",
        f"PidsLimit={pids}",
        f"PodmanArgs=--memory={memory_mb}m --memory-swap={memory_mb}m --cpus={cpus}",
        "LogDriver=journald",
        "Pull=never",
    ]


def render_project_quadlet(project: Project, release_dir: str) -> str:
    res = project.resources
    lines = [
        HEADER,
        "[Unit]",
        f"Description=steward workload {project.id}",
        "",
        "[Container]",
        f"ContainerName={project.id}",
        f"Image={image_tag(project.id, project.image)}",
        f"User={project.run_as}:{project.run_as}",
        f"UserNS=keep-id:uid={project.run_as},gid={project.run_as}",
        "Network=pasta",
        f"PublishPort=127.0.0.1:{project.host_port}:{project.container_port}",
        "Tmpfs=/tmp:rw,size=16m,mode=1777,noexec,nosuid,nodev",
        f"Environment=PORT={project.container_port}",
    ]
    if project.data_path:
        lines += [
            f"Volume=/srv/steward/projects/{project.id}/data:{project.data_path}:rw,nosuid,nodev",
            f"Environment=DATA_DIR={project.data_path}",
        ]
    if project.bundle:
        lines.append(f"Volume={release_dir}/bundles/{project.bundle}:/app:ro")
    if project.secrets:
        lines.append(f"EnvironmentFile=/etc/steward/secrets/projects/{project.id}.env")
    if project.command:
        lines.append("Exec=" + " ".join(project.command))
