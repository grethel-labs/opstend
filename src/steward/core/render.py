@dataclass(frozen=True)
class ApplicationProxyRoute:
    application: Slug
    service: Slug
    host: Hostname
    port: int


def application_proxy_routes(cfg: Config) -> tuple[ApplicationProxyRoute, ...]:
    """Select the internal TLS routes eligible for private graph deployment."""
    routes = []
    for app in sorted(cfg.applications, key=lambda item: item.id):
        for service in sorted(app.services, key=lambda item: item.id):
            for route in sorted(service.routes, key=lambda item: item.host):
                if route.tls != "internal":
                    raise ValueError(
                        f"{app.id}/{service.id}: application ACME routes are not available"
                    )
                if service.manage and service.deploy:
                    routes.append(
                        ApplicationProxyRoute(app.id, service.id, route.host, service.host_port)
                    )
    return tuple(routes)


def prepare_application_graphs(cfg: Config) -> list[dict[str, Any]]:
    """Prepare inert graph bindings; no deployment role consumes these yet."""
    used_users = {project.user for project in cfg.projects}
    used_units = {f"{project.id}.service" for project in cfg.projects}
    used_networks: set[str] = set()
    result = []
    for application in sorted(cfg.applications, key=lambda app: app.id):
        order = application.start_order()
        by_id = {service.id: service for service in application.services}
        shared_user = "stw-" + _graph_identifier("a", application.id)
        network = "steward-" + _graph_identifier("a", application.id)
        if application.isolation == "shared":
            pod_unit = _graph_identifier("a", application.id) + "-pod.service"
            if shared_user in used_users or network in used_networks or pod_unit in used_units:
                raise ValueError("application identity collision")
            used_users.add(shared_user)
            used_networks.add(network)
            used_units.add(pod_unit)
        services = []
        for service_id in order:
            service = by_id[service_id]
            stem = _graph_identifier("s", application.id, service.id)
            user = shared_user if application.isolation == "shared" else "stw-" + stem
            unit = stem + ".service"
            if unit in used_units or (application.isolation == "separate" and user in used_users):
                raise ValueError("application service identity collision")
            used_units.add(unit)
            used_users.add(user)
            services.append(
                {
                    "id": service.id,
                    "user": user,
                    "unit": unit,
                    "host_port": service.host_port,
                    "container_port": service.container_port,
                    "data_source": (
                        f"/srv/steward/applications/{application.id}/data/{service.id}"
                        if service.data_path is not None
                        else None
                    ),
                    "data_target": service.data_path,
                    "depends_on": sorted(service.depends_on),
                    # In separate isolation each directed edge resolves to the
                    # target's host loopback port. These bindings are inert;
                    # L02 must enforce them with the resolved service UID.
                    "loopback_dependencies": (
                        [
                            {"service": dependency, "port": by_id[dependency].host_port}
                            for dependency in sorted(service.depends_on)
                        ]
                        if application.isolation == "separate"
                        else []
                    ),
                }
            )
        result.append(
            {
                "id": application.id,
                "isolation": application.isolation,
                "network": network if application.isolation == "shared" else None,
                "service_hosts": (
                    [{"name": name, "address": "127.0.0.1"} for name in sorted(by_id)]
                    if application.isolation == "shared"
                    else []
                ),
                "start_order": order,
                "stop_order": application.stop_order(),
                "services": services,
            }
        )
    return result


