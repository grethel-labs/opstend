def _secret_lookup(ref: str) -> dict[str, str]:
    kind, _, target = ref.partition(":")
    if kind == "file":  # Ansible lookups need an absolute controller path
        target = str(Path(target).expanduser().resolve())
    return {"kind": kind, "target": target}


def prepare_application_registry(cfg: Config) -> dict[str, Any]:
    """Prepare root-registry bindings without enabling application operations.

    Identities, unit names and host data paths are derived from typed IDs; the
    container data target comes from the validated service contract. The actual
    executor registry and deployment remain guarded until group lifecycle and
    isolation are implemented and accepted.
    """
    graphs = {item["id"]: item for item in prepare_application_graphs(cfg)}
    applications = {}
    for app in sorted(cfg.applications, key=lambda item: item.id):
        graph = graphs[app.id]
        bindings = {item["id"]: item for item in graph["services"]}
        services = {}
        for service in sorted(app.services, key=lambda item: item.id):
            binding = bindings[service.id]
            stem = binding["unit"].removesuffix(".service")
            services[service.id] = {
                "manage": service.manage,
                "deploy": service.deploy,
                "user": binding["user"],
                "unit": binding["unit"],
                "container": stem,
                "lock": "project-" + stem,
                "depends_on": binding["depends_on"],
                "image": service.image,
                "source_revision": service.source_revision,
                "host_port": service.host_port,
                "routes": sorted(route.host for route in service.routes),
                "container_port": service.container_port,
                "data_source": binding["data_source"],
                "data_target": binding["data_target"],
                "run_as": service.run_as,
                "allow_restart": service.maintenance.allow_restart,
                "allow_backup_pause": service.maintenance.allow_backup_pause,
            }
        applications[app.id] = {
            "isolation": app.isolation,
            "on_critical": app.on_critical or "quarantine",
            **({"stateless": True} if app.stateless else {}),
            "lock": "application-" + _graph_identifier("a", app.id),
            "pod_unit": (
                _graph_identifier("a", app.id) + "-pod.service"
                if app.isolation == "shared" and any(service.manage for service in app.services)
                else None
            ),
            "services": services,
        }
    return {"config_revision": revision_id(effective(cfg)), "applications": applications}


