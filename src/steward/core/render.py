def _set(items: list[Any]) -> str:
    return "{ " + ", ".join(str(i) for i in items) + " }"


def _egress_chain(
    project: Project,
    *,
    name: str | None = None,
    loopback_ports: tuple[int, ...] = (),
    strict_outbound: bool = False,
) -> list[str]:
    name = name or f"egress_{project.id.replace('-', '_')}"
    lines = [f"    chain {name} {{"]
    lines.append(
        "        ct state established,related ct direction reply accept"
        if strict_outbound
        else "        ct state established,related accept"
    )
    if loopback_ports:
        lines.append(
            f'        oifname "lo" ip daddr 127.0.0.1 tcp dport {_set(list(loopback_ports))} accept'
        )
    egress = project.egress
    if egress.mode == "public-web":
        lines += [
            f'        oifname "lo" ip daddr {RESOLVER} {DNS_MATCH} accept',
        ]
    lines.append('        oifname "lo" counter reject')
    lines += [
        "        fib daddr type { local, broadcast, anycast, multicast } counter reject",
        # Link-local covers cloud metadata endpoints; never reachable, even by explicit rule.
        "        ip daddr 169.254.0.0/16 counter reject",
        "        ip6 daddr fe80::/10 counter reject",
    ]
    if egress.mode == "public-web":
        lines += [
            "        ip daddr @private4 counter reject",
            "        ip6 daddr @private6 counter reject",
            "        tcp dport { 80, 443 } accept",
        ]
    elif egress.mode == "rules":
        for rule in egress.rules:
            family = "ip6" if ":" in rule.cidr else "ip"
            lines.append(
                f"        {family} daddr {rule.cidr} {rule.proto} dport {_set(rule.ports)} accept"
            )
    lines += ["        counter reject", "    }"]
    return lines


def prepare_separate_application_egress(cfg: Config) -> list[dict[str, Any]]:
    """Prepare directed UID chains without installing or enabling them.

    Only explicitly declared, currently managed and deployed targets are
    admitted. Stopped managed services retain a default-deny chain so that a
    stray process does not fall through to the host's permissive output policy.
    Shared-UID applications need a separate egress contract.
    """
    prepared = {app["id"]: app for app in prepare_application_graphs(cfg)}
    result = []
    for app in sorted(cfg.applications, key=lambda item: item.id):
        if app.isolation != "separate":
            continue
        services = {service.id: service for service in app.services}
        bindings = {item["id"]: item for item in prepared[app.id]["services"]}
        for service_id in prepared[app.id]["start_order"]:
            service = services[service_id]
            if not service.manage:
                continue
            ports = tuple(
                sorted(
                    services[target].host_port
                    for target in service.depends_on
                    if service.deploy
                    if services[target].manage and services[target].deploy
                )
            )
            chain = "egress_" + _graph_identifier("s", app.id, service.id)
            policy = service if service.deploy else service.model_copy(update={"egress": Egress()})
            result.append(
                {
                    "application": app.id,
                    "service": service.id,
                    "user": bindings[service.id]["user"],
                    "chain": chain,
                    "deploy": service.deploy,
                    "loopback_ports": list(ports),
                    "content": "\n".join(
                        _egress_chain(
                            policy, name=chain, loopback_ports=ports, strict_outbound=True
                        )
                    ),
                }
            )
    return result


def prepare_shared_application_egress(cfg: Config) -> list[dict[str, Any]]:
    """Prepare one explicit union egress policy per shared service UID.

    A shared UID cannot enforce per-container egress. Every active service in
    that application therefore receives the union of their configured rules.
    The resulting chains are only a preview and are never installed here.
    """
    prepared = {app["id"]: app for app in prepare_application_graphs(cfg)}
    result = []
    for app in sorted(cfg.applications, key=lambda item: item.id):
        if app.isolation != "shared":
            continue
        managed = [service for service in app.services if service.manage]
        if not managed:
            continue
        active = sorted(
            (service for service in managed if service.deploy),
            key=lambda item: item.id,
        )
        public_web = any(service.egress.mode == "public-web" for service in active)
        merged: dict[tuple[str, str], set[int]] = {}
        for service in active:
            for rule in service.egress.rules:
                merged.setdefault((rule.cidr, rule.proto), set()).update(rule.ports)
        rules = [
            {"cidr": cidr, "proto": proto, "ports": sorted(ports)}
            for (cidr, proto), ports in sorted(merged.items())
        ]
        chain = "egress_" + _graph_identifier("a", app.id)
        lines = [
            f"    chain {chain} {{",
            "        ct state established,related ct direction reply accept",
        ]
        if public_web:
            lines.append(f'        oifname "lo" ip daddr {RESOLVER} {DNS_MATCH} accept')
        lines += [
            '        oifname "lo" counter reject',
            "        fib daddr type { local, broadcast, anycast, multicast } counter reject",
            "        ip daddr 169.254.0.0/16 counter reject",
            "        ip6 daddr fe80::/10 counter reject",
        ]
        for rule in rules:
            family = "ip6" if ":" in rule["cidr"] else "ip"
            lines.append(
                f"        {family} daddr {rule['cidr']} {rule['proto']} "
                f"dport {_set(rule['ports'])} accept"
            )
        if public_web:
            lines += [
                "        ip daddr @private4 counter reject",
                "        ip6 daddr @private6 counter reject",
                "        tcp dport { 80, 443 } accept",
            ]
        lines += ["        counter reject", "    }"]
        result.append(
            {
                "application": app.id,
                "user": prepared[app.id]["services"][0]["user"],
                "chain": chain,
                "active_services": [service.id for service in active],
                "inactive_services": sorted(
                    service.id
                    for service in app.services
                    if not service.manage or not service.deploy
                ),
                "public_web": public_web,
                "rules": rules,
                "content": "\n".join(lines),
            }
        )
    return result


def render_nftables(cfg: Config, ssh_port: int) -> str:
    """Complete ruleset for table `inet steward`.

    Service isolation is keyed on the socket owner UID: rootless containers
    reach the network through their user's pasta process, so `meta skuid`
    identifies the service for IPv4 and IPv6 alike.
    """
    return _render_nftables(cfg, ssh_port, deployed(cfg))


def _render_application_nftables_candidate(
    cfg: Config, ssh_port: int, routes: tuple[ApplicationProxyRoute, ...] | None = None
) -> str:
    """Render the complete graph-aware ruleset for acceptance testing."""
    if not cfg.hardening.firewall.manage:
        raise ValueError("application firewall candidate requires managed firewall")
    projects = [project for project in cfg.managed_projects if project.deploy]
    services = [
        service
        for application in cfg.applications
        for service in application.services
        if service.manage
    ]
    chains = prepare_separate_application_egress(cfg) + prepare_shared_application_egress(cfg)
    if routes is None:
        routes = application_proxy_routes(cfg)
    return _render_nftables(cfg, ssh_port, projects, services, chains, routes)


def _render_nftables(
    cfg: Config,
    ssh_port: int,
    projects: list[Project],
    services: Sequence[Service] = (),
    application_chains: Sequence[dict[str, Any]] = (),
    application_routes: tuple[ApplicationProxyRoute, ...] = (),
    *,
    repository_endpoint: tuple[ipaddress.IPv4Address | ipaddress.IPv6Address, int] | None = None,
) -> str:
    backends = [p.host_port for p in projects]
    legacy_proxy_ports = sorted(backends + [cfg.admin.backend_port, cfg.bot.port])
    application_ports = sorted(service.host_port for service in services)
    proxy_ports = sorted(set(legacy_proxy_ports) | {route.port for route in application_routes})
    proxy_denied_ports = sorted(set(application_ports) - set(proxy_ports))
    routes = [route for workload in projects for route in workload.routes]
    public = bool(cfg.bot.public_hostname or routes or application_routes)
    acme = bool(cfg.bot.public_hostname) or any(route.tls == "acme" for route in routes)

    verdicts = [f'"{p.user}" : jump egress_{p.id.replace("-", "_")}' for p in projects]
    verdicts += [f'"{item["user"]}" : jump {item["chain"]}' for item in application_chains]
    verdicts += [
        f'"{PROXY_USER}" : jump egress_proxy',
        f'"{API_USER}" : jump egress_platform',
        f'"{CONTROLLER_USER}" : jump egress_platform',
        f'"{COLLECTOR_USER}" : jump egress_platform',
        '"steward-bot" : jump egress_platform',
        '"steward-notify" : jump egress_notifications',
        '"steward-scan" : jump egress_notifications',
        '"steward-backup" : jump egress_backup',
        f'"{REPOSITORY_FETCH_USER}" : jump egress_repository_fetch',
    ]

    out = [
        "#!/usr/sbin/nft -f",
        HEADER,
        "table inet steward",
        "delete table inet steward",
        "",
        "table inet steward {",
        f"    set private4 {{ type ipv4_addr; flags interval; elements = {_set(PRIVATE_V4)} }}",
        f"    set private6 {{ type ipv6_addr; flags interval; elements = {_set(PRIVATE_V6)} }}",
        "",
        "    chain input {",
        "        type filter hook input priority filter; policy drop;",
    ]
    # Initial rendering can use the SSH transport port. Site preflight checks the
    # guest listener for collisions before applying any rules.
    if cfg.admin.port != ssh_port:
        lan = _resolved_admin_lan(cfg)
        incoming = 'iifname != "lo" ct direction original'
        if lan is not None:
            sources = [str(network) for network in (lan.allowed_sources or [lan.bind.network])]
            out.append(
                f'        iifname "{lan.interface}" ip saddr {_set(sources)} '
                f"ip daddr {lan.bind.ip} tcp dport {cfg.admin.port} "
                "ct direction original ct state new,established ct status != dnat accept"
            )
            out.append(
                f"        {incoming} meta l4proto tcp ct original proto-dst {cfg.admin.port} drop"
            )
        out.append(f"        {incoming} tcp dport {cfg.admin.port} drop")
    out += [
        "        ct state established,related accept",
        "        ct state invalid drop",
        '        iifname "lo" accept',
        "        icmp type { destination-unreachable, time-exceeded, parameter-problem } accept",
        "        icmp type echo-request limit rate 10/second accept",
        "        icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, "
        "parameter-problem, nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert } accept",
        "        icmpv6 type echo-request limit rate 10/second accept",
        "        udp sport 67 udp dport 68 accept",
        "        ip6 saddr fe80::/10 udp dport 546 accept",
        f"        tcp dport {ssh_port} accept",
    ]
    if public:
        out.append(f"        tcp dport {{ {WEB_PORT}, {WEBSECURE_PORT} }} ct status dnat accept")
    out += [
        "        counter",
        "    }",
        "",
        "    chain forward {",
        "        type filter hook forward priority filter; policy drop;",
        "    }",
        "",
    ]
    if public:
        out += [
            "    chain prerouting {",
            "        type nat hook prerouting priority dstnat; policy accept;",
            f"        fib daddr type local tcp dport 80 redirect to :{WEB_PORT}",
            f"        fib daddr type local tcp dport 443 redirect to :{WEBSECURE_PORT}",
            "    }",
            "",
        ]
    out += [
        "    chain output {",
        "        type filter hook output priority filter; policy accept;",
    ]
    if application_ports:
        # Apply reservations before legacy UID chains can accept established requests.
        allowed_users = [
            0,
            f'"{PROXY_USER}"',
            *(f'"{item["user"]}"' for item in application_chains),
        ]
        out += [
            f'        oifname "lo" tcp dport {_set(application_ports)} '
            f"meta skuid != {_set(allowed_users)} ct direction original counter "
            "reject with tcp reset",
        ]
    out += [
        f"        meta skuid vmap {_set(verdicts)}",
        '        oifname "lo" jump loopback_guard',
        "    }",
        "",
        "    chain egress_repository_fetch {",
    ]
    if repository_endpoint is not None:
        address, port = repository_endpoint
        family = "ip" if address.version == 4 else "ip6"
        out += [
            "        ct status dnat counter drop",
            f"        {family} daddr {address} tcp dport {port} accept",
        ]
    out += [
        "        counter drop",
        "    }",
        "",
        "    chain loopback_guard {",
        "        # Backends on host loopback are reachable by root (health checks) only;",
        "        # the proxy is admitted in its own chain.",
        f"        tcp dport {_set(legacy_proxy_ports)} meta skuid != 0 ct state new counter "
        "reject with tcp reset",
        "    }",
        "",
        "    chain egress_proxy {",
    ]
    if proxy_denied_ports:
        # A removed route must revoke the next request on an existing connection.
        out.append(
            f'        oifname "lo" tcp dport {_set(proxy_denied_ports)} '
            "ct direction original counter reject"
        )
    out += [
        "        ct state established,related accept",
        f'        oifname "lo" tcp dport {_set(proxy_ports)} accept',
    ]
    if acme:
        out += [
            f'        oifname "lo" ip daddr {RESOLVER} {DNS_MATCH} accept',
        ]
    out += [
        '        oifname "lo" counter reject',
        "        fib daddr type { local, broadcast, anycast, multicast } counter reject",
    ]
    if acme:
        out += [
            "        ip daddr @private4 counter reject",
            "        ip6 daddr @private6 counter reject",
            "        tcp dport 443 accept",
        ]
    out += [
        "        counter reject",
        "    }",
        "",
        "    chain egress_notifications {",
        f"        ip daddr {RESOLVER} {DNS_MATCH} accept",
        "        fib daddr type { local, broadcast, anycast, multicast } counter reject",
        "        ip daddr @private4 reject",
        "        ip6 daddr @private6 reject",
        "        tcp dport 443 accept",
        "        counter reject",
        "    }",
        "",
        "    chain egress_backup {",
        "        ct state established,related accept",
        '        oifname "lo" counter reject',
        "        fib daddr type { local, broadcast, anycast, multicast } counter reject",
        "        ip daddr 169.254.0.0/16 counter reject",
        "        ip6 daddr fe80::/10 counter reject",
    ]
    if cfg.backup.enabled and cfg.backup.endpoint is not None:
        for address in cfg.backup.endpoint.addresses:
            family = "ip6" if ":" in address else "ip"
            out.append(
                f"        {family} daddr {address} tcp dport {cfg.backup.endpoint.port} accept"
            )
    out += [
        "        counter reject",
        "    }",
        "",
        "    chain egress_platform {",
        "        ct state established,related accept",
        "        counter reject",
        "    }",
        "",
    ]
    for project in projects:
        out += _egress_chain(project) + [""]
    for item in application_chains:
        out += item["content"].splitlines() + [""]
    out[-1] = "}"
    return "\n".join(out) + "\n"


def render_backup_hosts(cfg: Config) -> str:
    lines = [HEADER, "127.0.0.1 localhost", "::1 localhost ip6-localhost"]
    endpoint = cfg.backup.endpoint
    if cfg.backup.enabled and endpoint:
        try:
            ipaddress.ip_address(endpoint.host)
        except ValueError:
            lines += [f"{address} {endpoint.host}" for address in endpoint.addresses]
    return "\n".join(lines) + "\n"


