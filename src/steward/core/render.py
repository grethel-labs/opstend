def _resolved_admin_lan(cfg: Config) -> AdminLan | None:
    lan = cfg.admin.lan
    if cfg.admin.access == "private-lan" and lan is not None and lan.bind is not None:
        return lan
    return None


def _admin_lan_hosts(cfg: Config) -> list[str]:
    lan = _resolved_admin_lan(cfg)
    if lan is None:
        return []
    return list(dict.fromkeys(str(ip) for ip in (lan.bind.ip, lan.advertise_ipv4) if ip))


def _admin_lan_port(cfg: Config) -> int:
    # The container has only the admin, web and websecure listeners.
    next_port = cfg.admin.port + 1
    if next_port > 65535 or next_port in (WEB_PORT, WEBSECURE_PORT):
        return cfg.admin.port - 1
    return next_port


def _internal_sans(cfg: Config, internal_hosts: Sequence[str]) -> list[str]:
    return [f"DNS:{host}" for host in internal_hosts] + [
        f"IP:{host}" for host in ["127.0.0.1", *_admin_lan_hosts(cfg)]
    ]


def render_traefik_static(cfg: Config, *, application_routes: bool = False) -> str:
    entry_points: dict[str, Any] = {"admin": {"address": f":{cfg.admin.port}"}}
    if _resolved_admin_lan(cfg) is not None:
        entry_points["admin-lan"] = {"address": f":{_admin_lan_port(cfg)}"}
    if has_public_routes(cfg) or application_routes:
        entry_points["web"] = {
            "address": f":{WEB_PORT}",
            "http": {"redirections": {"entryPoint": {"to": ":443", "scheme": "https"}}},
        }
        entry_points["websecure"] = {"address": f":{WEBSECURE_PORT}"}
    doc: dict[str, Any] = {
        "global": {"checkNewVersion": False, "sendAnonymousUsage": False},
        "entryPoints": entry_points,
        "providers": {"file": {"directory": "/etc/traefik/dynamic", "watch": True}},
        "log": {"level": "INFO"},
        "accessLog": {"format": "json"},
    }
    if cfg.proxy.acme_email:
        doc["certificatesResolvers"] = {
            "le": {
                "acme": {
                    "email": cfg.proxy.acme_email,
                    "storage": "/state/acme.json",
                    "tlsChallenge": {},
                }
            }
        }
    return HEADER + "\n" + yaml.safe_dump(doc, sort_keys=True)


def render_application_proxy_routes(routes: tuple[ApplicationProxyRoute, ...]) -> str:
    """Render only the root-managed, runtime application file for Traefik."""
    routers = {}
    services = {}
    for route in routes:
        service = _graph_identifier("app-", route.application, route.service)
        router = _graph_identifier("app-", route.application, route.service, route.host)
        services[service] = {
            "loadBalancer": {"servers": [{"url": f"http://{HOST_LOOPBACK_ALIAS}:{route.port}"}]}
        }
        routers[router] = {
            "rule": f"Host(`{route.host}`)",
            "entryPoints": ["websecure"],
            "service": service,
            "middlewares": ["security-headers"],
            "tls": {},
        }
    return (
        HEADER
        + "\n"
        + yaml.safe_dump({"http": {"routers": routers, "services": services}}, sort_keys=True)
    )


def render_traefik_dynamic(cfg: Config) -> str:
    routers: dict[str, Any] = {
        "admin": {
            "rule": "PathPrefix(`/`)",
            "entryPoints": ["admin"],
            "service": "admin",
            "middlewares": ["security-headers"],
            "tls": {},
        }
    }
    services: dict[str, Any] = {
        "admin": {
            "loadBalancer": {
                "servers": [{"url": f"http://{HOST_LOOPBACK_ALIAS}:{cfg.admin.backend_port}"}]
            }
        }
    }
    lan_hosts = _admin_lan_hosts(cfg)
    if lan_hosts:
        host_rule = " || ".join(f"Host(`{host}`)" for host in lan_hosts)
        routers["admin-lan"] = {
            **routers["admin"],
            "entryPoints": ["admin-lan"],
            "rule": f"({host_rule}) && !PathPrefix(`/bot/`)",
        }
    if cfg.bot.endpoints:
        services["bot"] = {
            "loadBalancer": {"servers": [{"url": f"http://{HOST_LOOPBACK_ALIAS}:{cfg.bot.port}"}]}
        }
        routers["bot-private"] = {
            "rule": "PathPrefix(`/bot/`)",
            "entryPoints": ["admin"],
            "service": "bot",
            "middlewares": ["security-headers"],
            "tls": {},
            "priority": 100,
        }
        if cfg.bot.public_hostname:
            routers["bot-public"] = {
                "rule": f"Host(`{cfg.bot.public_hostname}`) && PathPrefix(`/bot/`)",
                "entryPoints": ["websecure"],
                "service": "bot",
                "middlewares": ["security-headers"],
                "tls": {"certResolver": "le"},
            }
    for project in deployed(cfg):
        if not project.routes:
            continue
        services[f"p-{project.id}"] = {
            "loadBalancer": {
                "servers": [{"url": f"http://{HOST_LOOPBACK_ALIAS}:{project.host_port}"}]
            }
        }
        for index, route in enumerate(project.routes):
            routers[f"p-{project.id}-{index}"] = {
                "rule": f"Host(`{route.host}`)",
                "entryPoints": ["websecure"],
                "service": f"p-{project.id}",
                "middlewares": ["security-headers"],
                "tls": {"certResolver": "le"} if route.tls == "acme" else {},
            }
    doc = {
        "http": {
            "routers": routers,
            "services": services,
            "middlewares": {
                "security-headers": {
                    "headers": {
                        "stsSeconds": 31536000,
                        "contentTypeNosniff": True,
                        "frameDeny": True,
                        "referrerPolicy": "no-referrer",
                    }
                }
            },
        },
        "tls": {
            "certificates": [
                {
                    "certFile": "/etc/traefik/certs/internal.crt",
                    "keyFile": "/etc/traefik/certs/internal.key",
                }
            ],
            "options": {"default": {"minVersion": "VersionTLS12"}},
        },
    }
    if lan_hosts:
        leaf = doc["tls"]["certificates"][0]
        doc["tls"]["stores"] = {"default": {"defaultCertificate": leaf.copy()}}
    return HEADER + "\n" + yaml.safe_dump(doc, sort_keys=True)


