def _render_repository_fetch_candidate_vars(
    cfg: Config, *, release: dict[str, Any], ssh_port: int, endpoint: str
) -> dict[str, Any]:
    """Render the private fetch overlay on the canonical base deployment."""
    if not cfg.hardening.firewall.manage:
        raise ValueError("repository fetch candidate requires managed firewall")
    if len(cfg.repositories) != 1 or len(cfg.applications) != 1:
        raise ValueError("repository fetch candidate requires one repository and one application")
    application = cfg.applications[0]
    if len(application.services) != 1:
        raise ValueError("repository fetch candidate requires one service")
    service = application.services[0]
    if service.manage and service.deploy:
        raise ValueError("repository fetch candidate requires an inactive service")

    base = cfg.model_copy(update={"applications": [], "repositories": []})
    if unsupported := base.unavailable_features():
        raise ValueError(f"unavailable features: {', '.join(unsupported)}")

    from .repositories import _split_url, validate_endpoint

    repository = cfg.repositories[0]
    if (repository.application, repository.service) != (application.id, service.id):
        raise ValueError("repository fetch candidate requires the configured service binding")
    if repository.revision is None:
        raise ValueError("repository fetch candidate requires a full commit")
    address = ipaddress.ip_address(validate_endpoint(repository, endpoint))
    _, _, port = _split_url(repository.url)
    variables = render_vars(base, release=release, ssh_port=ssh_port)
    source = _render_nftables(base, ssh_port, deployed(base), repository_endpoint=(address, port))
    variables["steward_nftables"] = source
    variables["steward_repository_fetch"] = {
        "manifest": {
            "version": 1,
            "base_revision": variables["steward_config_revision"],
            "firewall_sha256": hashlib.sha256(source.encode("utf-8")).hexdigest(),
            "endpoint": str(address),
            "credential_required": repository.credential is not None,
            "handoff": {
                "contract": repository.contract.model_dump(mode="json")
                if repository.contract
                else None,
            },
            "repository": repository.model_dump(
                mode="json",
                include={
                    "id",
                    "application",
                    "service",
                    "url",
                    "ref",
                    "revision",
                    "host_key",
                    "allow_private_network",
                },
            ),
        },
        "credential": _secret_lookup(repository.credential) if repository.credential else None,
    }
    return variables


def _render_local_ai_candidate_vars(
    cfg: Config, *, release: dict[str, Any], ssh_port: int
) -> dict[str, Any]:
    """Render a private Ollama overlay on the canonical API deployment."""
    ai = cfg.ai
    if cfg.profile != "local-ai" or ai.provider != "ollama":
        raise ValueError("local Ollama candidate requires the local-ai profile and ollama provider")
    if ai.local_only is not True:
        raise ValueError("local Ollama candidate requires ai.local_only")
    if not ai.model or not isinstance(ai.local, AiLocal):
        raise ValueError("local Ollama candidate requires ai.model and ai.local")
    if ai.local.license_ack is not True:
        raise ValueError("local Ollama candidate requires ai.local.license_ack")
    if ai.base_url not in (None, f"http://{LISTEN}"):
        raise ValueError("local Ollama candidate uses a fixed loopback endpoint")

    base = cfg.model_copy(update={"profile": "api", "ai": Ai()})
    if unsupported := base.unavailable_features():
        raise ValueError(f"unavailable features: {', '.join(unsupported)}")
    variables = render_vars(base, release=release, ssh_port=ssh_port)
    variables["steward_ollama_local"] = {
        "ai": ai.model_dump(mode="json"),
        "reserved_memory_mb": variables["steward_required_memory_mb"],
    }
    return variables


def _render_local_ai_selection_candidate_vars(
    cfg: Config,
    *,
    release: dict[str, Any],
    ssh_port: int,
    manifest_sha256: str,
    advice: bool = False,
) -> dict[str, Any]:
    """Extend the private G2 overlay with the W30 publication binding."""
    from .inference_deployment import (
        _Candidate,
        _validate_advice_budget,
        _validate_advice_routes,
        _validate_local_ai,
    )

    variables = _render_local_ai_candidate_vars(cfg, release=release, ssh_port=ssh_port)
    _validate_local_ai(cfg.ai)
    if type(advice) is not bool:
        raise ValueError("candidate advice opt-in must be a boolean")
    if advice:
        _validate_advice_routes(cfg)
        _validate_advice_budget(cfg.ai)
    try:
        version, wheel = release["version"], release["wheel"]
        wheel_sha256 = release["files"][wheel]
    except (KeyError, TypeError) as error:
        raise ValueError("missing release wheel binding") from error
    if wheel != f"steward-{version}-py3-none-any.whl":
        raise ValueError("invalid release wheel name")
    variables["steward_inference_candidate"] = _Candidate(
        version=1,
        revision=variables["steward_config_revision"],
        release=version,
        wheel_sha256=wheel_sha256,
        manifest_sha256=manifest_sha256,
        **({"advice": True} if advice else {}),
    ).model_dump(mode="json")
    return variables


def _render_application_candidate_vars(
    cfg: Config, *, release: dict[str, Any], ssh_port: int
) -> dict[str, Any]:
    """Render private launch fixtures for the operator's application acceptance tests."""
    unsupported = [feature for feature in cfg.unavailable_features() if feature != "applications"]
    if unsupported:
        raise ValueError(f"unavailable features: {', '.join(unsupported)}")
    if not cfg.applications:
        return render_vars(cfg, release=release, ssh_port=ssh_port)
    if not cfg.hardening.firewall.manage:
        raise ValueError("application launch candidate requires managed firewall")

    routes = application_proxy_routes(cfg)
    active = []
    by_application = {}
    for app in cfg.applications:
        by_id = {service.id: service for service in app.services}
        by_application[app.id] = app, by_id
        for service in app.services:
            label = f"{app.id}/{service.id}"
            if not service.manage:
                continue
            if service.host_port == ssh_port:
                raise ValueError(f"{label}: host port collides with SSH port {ssh_port}")
            if service.deploy:
                for dependency in service.depends_on:
                    if not (by_id[dependency].manage and by_id[dependency].deploy):
                        raise ValueError(f"{label}: prerequisite {dependency} must be active")
                active.append(service)

    legacy_cfg = cfg.model_copy(update={"applications": []})
    variables = render_vars(legacy_cfg, release=release, ssh_port=ssh_port)
    if routes:
        proxy = variables["steward_proxy"]
        proxy.update(render_application_proxy_configuration(cfg, routes))
        proxy["application_runtime"] = APPLICATION_PROXY_DYNAMIC
        variables["steward_public_routes"] = True
    registry = prepare_application_registry(cfg)
    revision = registry["config_revision"]
    applications = []
    users = set()
    for quadlets in render_application_quadlets(cfg, variables["steward_release_dir"]):
        if not quadlets["services"]:
            continue
        app, by_id = by_application[quadlets["id"]]
        services = []
        for binding in quadlets["services"]:
            service = by_id[binding["id"]]
            services.append(
                {
                    **binding,
                    "image": service.image,
                    "image_tag": image_tag(binding["unit"].removesuffix(".service"), service.image),
                    "secrets": [{"name": s.name, **_secret_lookup(s.ref)} for s in service.secrets],
                    "host_port": service.host_port,
                    "health_path": service.health.path,
                    "health_timeout_s": service.health.timeout_s,
                }
            )
            users.add(binding["user"])
        applications.append(
            {
                "id": app.id,
                "isolation": app.isolation,
                "pod": quadlets["pod"],
                "services": services,
            }
        )

    chains = prepare_separate_application_egress(cfg) + prepare_shared_application_egress(cfg)
    variables["steward_config_revision"] = revision
    variables["steward_desired_config"] = effective(cfg)
    variables["steward_registry"].update(registry)
    variables["steward_backup"]["config_revision"] = revision
    variables["steward_required_memory_mb"] += sum(
        service.resources.memory_mb for service in active
    )
    variables["steward_listen_ports"] = sorted(
        variables["steward_listen_ports"] + [service.host_port for service in active]
    )
    variables["steward_nftables"] = _render_application_nftables_candidate(cfg, ssh_port, routes)
    variables["steward_applications"] = applications
    variables["steward_application_users"] = [
        {"name": name, "home": f"/srv/steward/application-users/{name}"} for name in sorted(users)
    ]
    variables["steward_application_egress"] = [
        {"user": chain["user"], "chain": chain["chain"]} for chain in chains
    ]
    return variables
